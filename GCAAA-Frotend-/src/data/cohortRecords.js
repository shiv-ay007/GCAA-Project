// Helper to determine batch number label based on cohort and year
export const getBatchNo = (year, cohort = 'all') => {
  if (!year) return '';
  const yr = typeof year === 'string' ? year : year.toString();
  const num = parseInt(yr, 10);
  if (isNaN(num)) return yr;
  
  switch (cohort) {
    case 'all':
      if (num >= 1985 && num <= 2025) {
        return `Batch ${num - 1984} (${num})`;
      }
      return yr;
    case 'b-arch':
      return `B01${padded}`;
    case 'm-arch':
      if (num >= 2015) return `M.Arch Batch ${num - 2014} (${num})`;
      return yr;
    case 'murp':
      if (num >= 2020) return `MURP Batch ${num - 2019} (${num})`;
      return yr;
    case 'miend':
      if (num >= 2020) return `MIEND Batch ${num - 2019} (${num})`;
      return yr;
    case 'mind':
      if (num >= 2023) return `MIND Batch ${num - 2022} (${num})`;
      return yr;
    default:
      return yr;
  }
};

// Helper to format membership number
export const getMembershipNo = (sno, cohort = 'all', year = '') => {
  const padded = String(sno).padStart(3, '0');
  switch (cohort) {
    case 'all': {
      const num = parseInt(year, 10);
      if (!isNaN(num) && num >= 1985) {
        const b = String(num - 1984).padStart(2, '0');
        return `U${b}${padded}`;
      }
      return `D01${padded}`;
    }
    case 'm-arch':
      return `M10${padded}`;
    case 'murp':
      return `M20${padded}`;
    case 'miend':
      return `M30${padded}`;
    case 'mind':
      return `M40${padded}`;
    default:
      return `GCA${padded}`;
  }
};

